// Regenerate from the pinned @mdi/js and @mdi/svg packages:
// - web/mdi-catalog.json: [[name without "mdi:", "aliases and tags"], ...],
//   deprecated icons omitted (searched lazily by the icon picker);
// - shared/marker-icon-paths.mjs: path data for the suggested icons only, so
//   the startup bundles never import the whole @mdi/js set.
// Run from rooms-app/: node tools/mdi-catalog.mjs
import { readFile, writeFile } from "node:fs/promises";
const meta = JSON.parse(
  await readFile(
    new URL("../node_modules/@mdi/svg/meta.json", import.meta.url),
  ),
);
const rows = meta
  .filter((icon) => !icon.deprecated)
  .map((icon) => [
    icon.name,
    [...new Set([...(icon.aliases || []), ...(icon.tags || [])])]
      .join(" ")
      .toLowerCase(),
  ])
  .sort((a, b) => a[0].localeCompare(b[0]));
await writeFile(
  new URL("../web/mdi-catalog.json", import.meta.url),
  JSON.stringify(rows) + "\n",
);
const paths = await import("@mdi/js");
const suggested = [
  ...(
    await readFile(
      new URL("../shared/marker-icons.mjs", import.meta.url),
      "utf8",
    )
  ).matchAll(/\["(mdi:[a-z0-9-]+)",/g),
].map((match) => match[1]);
const exportName = (icon) =>
  "mdi" +
  icon
    .slice(4)
    .split("-")
    .map((part) => part[0].toUpperCase() + part.slice(1))
    .join("");
const lines = suggested.map((icon) => {
  const path = paths[exportName(icon)];
  if (!path) throw new Error(`Unknown suggested icon ${icon}`);
  return `  ${JSON.stringify(icon)}:\n    ${JSON.stringify(path)},`;
});
await writeFile(
  new URL("../shared/marker-icon-paths.mjs", import.meta.url),
  `// Generated by tools/mdi-catalog.mjs from @mdi/js; do not edit.\nexport const SUGGESTED_ICON_PATHS = {\n${lines.join("\n")}\n};\n`,
);
console.log(
  `Wrote ${rows.length} Material Design icons and ${suggested.length} suggestion paths.`,
);
